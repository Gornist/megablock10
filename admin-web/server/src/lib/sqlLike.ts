/**
 * Экранирует спецсимволы LIKE ('%', '_', '\\') — использовать вместе с "ESCAPE '\\'".
 * Без этого '_' в id контейнера ("pump_1") совпадал с любым символом, и в сводку узла попадали
 * записи соседнего контейнера "pumpX1"; '%'/'_' в строке поиска по источнику работали как шаблон.
 */
export function escapeLike(text: string): string {
  return text.replace(/[\\%_]/g, "\\$&");
}
