"""Единая палитра 3D-ассетов «Сети». Без bpy: её читают и скрипты Blender, и проверки.

Источник цветов — docs/ux/ui-style-guide.md, раздел 2 (токены). Смысл цвета тот же, что в приложении:
  acc    бирюзовый — «активно», то, с чем можно взаимодействовать; неон тира BASE
  warn   оранжевый — «ждёт действия»: закрытое хранилище, зашифрованный шард; неон тира HARD
  bad    красный   — опасность: датчик, запертый выход; неон тира NIGHTMARE
  money  жёлтый    — добыча (шард)
  ok     зелёный   — «успех»: открытое хранилище
  chrome тусклый красный — обвязка, неживое (мёртвая дека)
Лайм и тема «успех» из гайдлайна — только экраны взлома приложения, в мире их нет.

Тела (тёмная заливка) — производные от plate/surface гайдлайна, чуть светлее: под тусклым светом узла они должны читаться.
"""

# токены гайдлайна (sRGB)
ACC = "#5EF6FF"
MONEY = "#F5D547"
OK = "#43F08F"
WARN = "#FF9F43"
BAD = "#FF5A50"
CHROME = "#C65A52"
CHROME_DIM = "#5A2629"

# тела тиров: BASE — от surface (#0E1718), HARD и NIGHTMARE — от plate (#150D10) в сторону своего неона
TIERS = {
    "BASE": {"suffix": "", "body": "#15272B", "neon": ACC},
    "HARD": {"suffix": "_hard", "body": "#2B1F14", "neon": WARN},
    "NIGHTMARE": {"suffix": "_nightmare", "body": "#2E1215", "neon": BAD},
}

# тело предметов (props): нейтральный графит, не зависит от тира
PROP_BODY = "#2A2D31"

# сила свечения (emission strength): окружение тусклее, предметы заметнее
NEON_ENV = 1.6
NEON_PROP = 2.2


def hex_rgb(h):
    """'#RRGGBB' -> (r, g, b) sRGB 0..1."""
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))


def _lin(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def linear(h):
    """'#RRGGBB' -> (r, g, b) в линейном пространстве (так хранит glTF и принимает Blender)."""
    return tuple(_lin(c) for c in hex_rgb(h))
