def neon_strength(neon_hex, default):
    """Сила свечения неона: сигнальные цвета (warn, ok, bad) — NEON_SIGNAL, остальные — default (NEON_ENV или NEON_PROP)."""
    return NEON_SIGNAL if neon_hex.upper() in SIGNAL else default


def hex_rgb(h):
    """'#RRGGBB' -> (r, g, b) sRGB 0..1."""
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))


def _lin(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def linear(h):
    """'#RRGGBB' -> (r, g, b) в линейном пространстве (так хранит glTF и принимает Blender)."""
    return tuple(_lin(c) for c in hex_rgb(h))
